"""Render EOS configuration from `DeviceIntent` (INIT-001/SPEC-005).

Pure functions with no NetBox or network access: given intent, return text. That
makes the exact bytes a switch receives testable, which is the part a demo cannot
afford to get wrong live.
"""

from __future__ import annotations

from .fabric import DeviceIntent, Peer, ServerPort, TenantVlan

HEADER = """!
! ============================================================================
! {hostname} - Arista EOS configuration
! Generated by the netbox-demo plugin from NetBox intent
! Role: {role}   ASN: {asn}
! ============================================================================
!
hostname {hostname}
!
no aaa root
!
"""


def _services(i: DeviceIntent) -> str:
    s = i.services
    lines = [
        "! --- Standard fabric services ---",
        "!",
        "service routing protocols model multi-agent",
        "!",
        f"clock timezone {s.timezone}",
        "!",
    ]
    lines += [f"ntp server vrf MGMT {server}" for server in s.ntp_servers]
    lines += [f"ip name-server vrf MGMT {server}" for server in s.dns_servers]
    lines += [
        "!",
        f"ip domain-name {s.domain_name}",
        "!",
        f"logging host {s.syslog_host} {s.syslog_port}",
        f"logging vrf MGMT host {s.syslog_host}",
        "logging buffered 65536",
        "!",
        f"snmp-server community {s.snmp_community} ro",
        "snmp-server vrf MGMT",
        f"snmp-server contact {s.snmp_contact}",
        f"snmp-server location {s.snmp_location}",
        "snmp-server enable traps",
        "!",
        "lldp run",
        f"lldp timer {s.lldp_timer}",
        f"lldp hold-time {s.lldp_hold_time}",
        "!",
        f"errdisable recovery interval {s.errdisable_interval}",
        "errdisable recovery cause bpduguard",
        "!",
        "management ssh",
        f"   idle-timeout {s.ssh_idle_timeout}",
        "   connection-limit 10",
        "   vrf MGMT",
        "      no shutdown",
        "!",
        "management console",
        f"   idle-timeout {s.console_idle_timeout}",
        "!",
        "banner login",
        s.banner,
        "EOF",
        "!",
    ]
    return "\n".join(lines)


def _management(i: DeviceIntent, *, eapi_vrf: str = "MGMT", mgmt_interface: bool = True) -> str:
    """Management reachability, eAPI, and the default route.

    Two things are platform-dependent and must not be hardcoded:

    * `eapi_vrf` — binding eAPI into a VRF is the correct production posture and
      what local ContainerLab uses. On Kubernetes via c9s the VRF-bound listener
      lands in a network namespace c9s does not interpose, so 443 stops answering
      while SSH on 22 keeps working. Pushing that block would break the demo's own
      control channel mid-run, so the caller decides.
    * `mgmt_interface` — cEOS on c9s binds eth0 and never adopts Management0, so
      rendering that interface produces a config for an interface the switch does
      not have. The address is then supplied by the platform, not by EOS.
    """
    lines = [
        "! --- Management ---",
        "!",
        f"vrf instance {i.mgmt_vrf}",
        "!",
    ]

    if mgmt_interface:
        lines += [
            "interface Management0",
            "   description OOB management",
            f"   vrf {i.mgmt_vrf}",
        ]
        if i.mgmt_address:
            lines.append(f"   ip address {i.mgmt_address}")
        lines += ["   no shutdown", "!"]
    else:
        lines += [
            "! Management0 is platform-managed here (cEOS binds eth0 on c9s) and",
            "! is never adopted by EOS, so it is deliberately not configured.",
            "!",
        ]

    lines += [
        f"ip route vrf {i.mgmt_vrf} 0.0.0.0/0 {i.mgmt_gateway}",
        "!",
        "management api http-commands",
        "   protocol https",
        "   no shutdown",
    ]
    if eapi_vrf:
        lines += [f"   vrf {eapi_vrf}", "      no shutdown"]
    lines.append("!")
    return "\n".join(lines)


def _loopbacks(i: DeviceIntent) -> str:
    lines = [
        "! --- Loopbacks ---",
        "!",
        "interface Loopback0",
        "   description Router ID",
        f"   ip address {i.router_id}/32",
        "!",
    ]
    if i.is_leaf and i.vtep_address:
        lines += [
            "interface Loopback1",
            "   description VXLAN VTEP source",
            f"   ip address {i.vtep_address}/32",
            "!",
        ]
    return "\n".join(lines)


def _fabric_interfaces(i: DeviceIntent) -> str:
    if not i.fabric_interfaces:
        return ""
    lines = ["! --- Fabric (routed) links ---", "!"]
    for intf in sorted(i.fabric_interfaces, key=lambda x: x.name):
        lines += [
            f"interface {intf.name}",
            f"   description {intf.description}",
            f"   mtu {intf.mtu}",
            "   no switchport",
            f"   ip address {intf.address}",
            "   no shutdown",
            "!",
        ]
    return "\n".join(lines)


def _vlans(i: DeviceIntent) -> str:
    if not i.is_leaf or not i.vlans:
        return ""
    lines = ["! --- Tenant VLANs ---", "!"]
    for vlan in i.vlans:
        lines += [f"vlan {vlan.vlan_id}", f"   name {vlan.name}", "!"]
    lines.append("")
    for vlan in i.vlans:
        lines += [
            f"interface Vlan{vlan.vlan_id}",
            f"   description {vlan.name} anycast gateway",
            f"   mtu {vlan.mtu}",
            f"   ip address {vlan.svi_address}",
            "   no autostate",
            *[f"   ip helper-address {helper}" for helper in vlan.ip_helpers],
            "   ip virtual-router address " + vlan.svi_address.split("/")[0],
            "!",
        ]
    return "\n".join(lines)


def _server_ports(i: DeviceIntent) -> str:
    if not i.server_ports:
        return ""
    lines = ["! --- Server-facing ports ---", "!"]
    for port in sorted(i.server_ports, key=lambda p: p.name):
        lines += _render_port(port)
    return "\n".join(lines)


def _render_port(port: ServerPort) -> list[str]:
    """Render the member port only; the bundle is rendered separately by `_port_channels`."""
    lines = [f"interface {port.name}", f"   description {port.description}"]
    if port.port_channel:
        channel_id = port.port_channel.rsplit("-", 1)[-1]
        lines.append(f"   channel-group {channel_id} mode active")
        lines.append("   no shutdown")
        lines.append("!")
        return lines

    if port.mode == "trunk":
        vlans = ",".join(str(v) for v in port.trunk_vlans)
        lines += [
            "   switchport mode trunk",
            f"   switchport trunk allowed vlan {vlans}",
            f"   mtu {port.mtu}",
        ]
    else:
        lines += [
            "   switchport mode access",
            f"   switchport access vlan {port.access_vlan}",
            f"   mtu {port.mtu}",
        ]
    lines.append("   no shutdown" if port.enabled else "   shutdown")
    lines.append("!")
    return lines


def _port_channels(i: DeviceIntent) -> str:
    bundles: dict[str, ServerPort] = {}
    for port in i.server_ports:
        if port.port_channel:
            bundles[port.port_channel] = port
    if not bundles:
        return ""
    lines = ["! --- Server port-channels ---", "!"]
    for name in sorted(bundles):
        port = bundles[name]
        lines += [f"interface {name}", f"   description {port.description} bundle"]
        if port.mode == "trunk":
            vlans = ",".join(str(v) for v in port.trunk_vlans)
            lines += [
                "   switchport mode trunk",
                f"   switchport trunk allowed vlan {vlans}",
            ]
        else:
            lines += [
                "   switchport mode access",
                f"   switchport access vlan {port.access_vlan}",
            ]
        lines += [f"   mtu {port.mtu}", "   no shutdown" if port.enabled else "   shutdown", "!"]
    return "\n".join(lines)


def _mlag(i: DeviceIntent) -> str:
    m = i.mlag
    if not i.is_leaf or m is None:
        return ""
    local = m.local_address
    lines = [
        "! --- MLAG ---",
        "!",
        f"vlan {m.peer_link_vlan}",
        "   name MLAG-PEER-LINK",
        "   trunk group MLAG",
        "!",
    ]
    for member in m.peer_link_members:
        lines += [
            f"interface {member}",
            "   description MLAG peer link",
            "   channel-group 2000 mode active",
            "!",
        ]
    lines += [
        f"interface {m.peer_link}",
        "   description MLAG peer link bundle",
        "   switchport mode trunk",
        "   switchport trunk group MLAG",
        "!",
        f"interface Vlan{m.peer_link_vlan}",
        "   description MLAG peer link SVI",
        "   no autostate",
        f"   ip address {local}",
        "!",
        "mlag configuration",
        f"   domain-id NETBOX-DEMO-{m.domain_id}",
        f"   local-interface Vlan{m.peer_link_vlan}",
        f"   peer-link {m.peer_link}",
        f"   peer-address {m.peer_address}",
        "   reload-delay mlag 300",
        "   reload-delay non-mlag 330",
        "!",
    ]
    return "\n".join(lines)


def _bgp(i: DeviceIntent) -> str:
    lines = [
        "! --- BGP underlay + EVPN overlay ---",
        "!",
        "ip routing",
        "!",
        f"router bgp {i.asn}",
        f"   router-id {i.router_id}",
        "   no bgp default ipv4-unicast",
        "   distance bgp 20 200 200",
        "   maximum-paths 4 ecmp 4",
        "   graceful-restart restart-time 300",
        "   graceful-restart",
        "!",
    ]
    groups: dict[str, list[Peer]] = {}
    for peer in i.peers:
        groups.setdefault(peer.peer_group, []).append(peer)

    for group, peers in groups.items():
        lines.append(f"   peer group {group}")
        lines.append(f"      remote-as {peers[0].remote_as}")
        lines.append("      send-community extended")
        if "EVPN" in group:
            lines += ["      multihop 3", "      update-source Loopback0"]
        lines.append("!")

    for peer in i.peers:
        lines += [
            f"   neighbor {peer.address} peer group {peer.peer_group}",
            f"   neighbor {peer.address} description {peer.description}",
            "!",
        ]

    lines += ["   address-family ipv4", "      redistribute connected"]
    for group in groups:
        if "IPV4" in group:
            lines.append(f"      neighbor {group} activate")
    lines.append("!")

    if i.is_leaf:
        lines.append("   address-family evpn")
        for group in groups:
            if "EVPN" in group:
                lines.append(f"      neighbor {group} activate")
        lines.append("!")
        for vlan in i.vlans:
            lines += [
                f"   vlan {vlan.vlan_id}",
                f"      rd {i.router_id}:{vlan.vlan_id}",
                f"      route-target both {vlan.vni}:{vlan.vlan_id}",
                "      redistribute learned",
                "!",
            ]
    return "\n".join(lines)


def _vxlan(i: DeviceIntent) -> str:
    if not i.is_leaf or not i.vtep_address:
        return ""
    lines = [
        "! --- VXLAN ---",
        "!",
        "interface Vxlan1",
        "   description VXLAN VTEP",
        "   vxlan source-interface Loopback1",
        "   vxlan udp-port 4789",
    ]
    for vlan in i.vlans:
        lines.append(f"   vxlan vlan {vlan.vlan_id} vni {vlan.vni}")
    lines.append("   vxlan vlan 4094 vni 4094")
    lines += ["!", "ip virtual-router mac-address " + i.anycast_gateway_mac, "!"]
    return "\n".join(lines)


def render_device(
    intent: DeviceIntent,
    *,
    eapi_vrf: str = "MGMT",
    mgmt_interface: bool = True,
) -> str:
    """Return the complete EOS configuration for one switch.

    The two keyword arguments are platform facts, not preferences; see
    `_management` for why.
    """
    sections = [
        HEADER.format(hostname=intent.hostname, role=intent.role, asn=intent.asn),
        _management(intent, eapi_vrf=eapi_vrf, mgmt_interface=mgmt_interface),
        _loopbacks(intent),
        _fabric_interfaces(intent),
        _vlans(intent),
        _server_ports(intent),
        _port_channels(intent),
        _mlag(intent),
        _bgp(intent),
        _vxlan(intent),
        _services(intent),
        "!",
        "end",
    ]
    body = "\n".join(section for section in sections if section)
    # Collapse the accidental runs of blank lines an include-based template leaves.
    while "\n\n\n" in body:
        body = body.replace("\n\n\n", "\n\n")
    return body.rstrip() + "\n"


def render_all(
    intents: dict[str, DeviceIntent],
    *,
    eapi_vrf: str = "MGMT",
    mgmt_interface: bool = True,
) -> dict[str, str]:
    """Render every device, keyed by hostname."""
    return {
        host: render_device(intent, eapi_vrf=eapi_vrf, mgmt_interface=mgmt_interface)
        for host, intent in intents.items()
    }


def sanity_check(configs: dict[str, str]) -> list[str]:
    """Cheap pre-push checks, so an obviously broken config never reaches a switch."""
    problems: list[str] = []
    for host, cfg in configs.items():
        if not cfg.strip():
            problems.append(f"{host}: rendered configuration is empty")
            continue
        if f"hostname {host}" not in cfg:
            problems.append(f"{host}: configuration does not set hostname {host}")
        if "router bgp" not in cfg:
            problems.append(f"{host}: configuration has no BGP process")
        if "\t" in cfg:
            problems.append(f"{host}: configuration contains tab characters")
    return problems
